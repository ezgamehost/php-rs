#!/usr/bin/env python3
"""Generate Rust HTML mappings from an upstream PHP source tree's html_tables.h."""
import argparse
from pathlib import Path
import subprocess
import tempfile

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('php_source', type=Path)
parser.add_argument('--output', type=Path, default=Path('src/runtime/html/tables.rs'))
args = parser.parse_args()

extractor = r'''
#include <stdint.h>
#include <stdio.h>
#include "html_tables.h"
static void encode(const entity_stage1_row *table, int version) {
    for (unsigned cp = 0; cp < 0x1e000; cp++) {
        const entity_stage3_row *r = &table[cp >> 12][(cp >> 6) & 63][cp & 63];
        if (!r->data.ent.entity) continue;
        if (!r->ambiguous) printf("E%d\t%u\t0\t%s\n", version, cp, r->data.ent.entity);
        else {
            const entity_multicodepoint_row *rows = r->data.multicodepoint_table;
            if (rows[0].leading_entry.default_entity)
                printf("E%d\t%u\t0\t%s\n", version, cp, rows[0].leading_entry.default_entity);
            for (unsigned i = 1; i <= rows[0].leading_entry.size; i++)
                printf("E%d\t%u\t%u\t%s\n", version, cp, rows[i].normal_entry.second_cp, rows[i].normal_entry.entity);
        }
    }
}
static void decode(const entity_ht *table, int version) {
    for (unsigned i = 0; i < table->num_elems; i++)
        for (const entity_cp_map *r = table->buckets[i]; r->entity; r++)
            printf("D%d\t%u\t%u\t%s\n", version, r->codepoint1, r->codepoint2, r->entity);
}
int main(void) {
    encode(entity_ms_table_html4, 4); encode(entity_ms_table_html5, 5);
    decode(&ent_ht_html4, 4); decode(&ent_ht_html5, 5);
    for (unsigned cs = 1; cs < 9; cs++)
        for (unsigned b = 0; b < 256; b++)
            printf("S\t%u\t%u\t%u\n", cs, b, enc_to_uni_index[cs]->inner[b >> 6]->uni_cp[b & 63]);
    for (unsigned i = 0; i < sizeof(charset_map)/sizeof(*charset_map); i++)
        printf("A\t%u\t%s\n", charset_map[i].charset, charset_map[i].codeset);
}
'''
with tempfile.TemporaryDirectory(prefix='php-rs-html-') as temp:
    source, binary = Path(temp) / 'extract.c', Path(temp) / 'extract'
    source.write_text(extractor)
    subprocess.run(['cc', '-std=c99', '-I', str(args.php_source / 'ext/standard'),
                    str(source), '-o', str(binary)], check=True)
    lines = subprocess.check_output([str(binary)], text=True).splitlines()

entities = {key: [] for key in ['E4', 'E5', 'D4', 'D5']}
charsets = [[None] * 256 for _ in range(8)]
aliases = []
for line in lines:
    kind, *fields = line.split('\t')
    if kind in entities:
        first, second, name = fields
        entities[kind].append((int(first), int(second), name))
    elif kind == 'S':
        charset, byte, code = map(int, fields)
        charsets[charset - 1][byte] = code
    else:
        charset, name = fields
        aliases.append((name.lower(), int(charset)))

output = ['// Generated by tools/generate_html_tables.py from PHP 8.5.0 html_tables.h.',
          '// Copyright (c) The PHP Group. See THIRD_PARTY_NOTICES.md.',
          '#![allow(clippy::unreadable_literal)]', '']
for key, rows in entities.items():
    if key.startswith('D'):
        rows.sort(key=lambda row: row[2])
        output.append(f'pub(super) const {key}: &[(&[u8], u32, u32)] = &[')
        output.extend(f'    (b"{name}", {first:#x}, {second:#x}),' for first, second, name in rows)
    else:
        output.append(f'pub(super) const {key}: &[(u32, u32, &[u8])] = &[')
        output.extend(f'    ({first:#x}, {second:#x}, b"{name}"),' for first, second, name in rows)
    output.append('];\n')
output.append('pub(super) const SINGLE_BYTE: [[u16; 256]; 8] = [')
for charset in charsets:
    assert all(code is not None for code in charset)
    output.append('    [')
    for start in range(0, 256, 8):
        output.append('        ' + ', '.join(f'{code:#06x}' for code in charset[start:start + 8]) + ',')
    output.append('    ],')
output.append('];\n')
output.append('pub(super) const ALIASES: &[(&[u8], usize)] = &[')
output.extend(f'    (b"{name}", {charset}),' for name, charset in aliases)
output.append('];\n')
args.output.parent.mkdir(parents=True, exist_ok=True)
args.output.write_text('\n'.join(output))
subprocess.run(['rustfmt', '--edition', '2024', str(args.output)], check=True)
print('Generated', args.output, {key: len(value) for key, value in entities.items()})
