#!/usr/bin/env python3
"""Extract reflection metadata for implemented builtins from a PHP 8.5 binary."""
import argparse
import json
from pathlib import Path
import re
import subprocess

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('php', type=Path)
parser.add_argument('--output', type=Path, default=Path('src/runtime/reflection/native_signatures.rs'))
args = parser.parse_args()
source = Path('src/runtime/builtins.rs').read_text().split('fn lookup(', 1)[1].split('fn parameters(', 1)[0]
names = sorted(set(re.findall(r'b"([a-z_0-9]+)"', '\n'.join(line.split('=>')[0] for line in source.splitlines() if '=>' in line))))
extractor = r'''
if (PHP_VERSION !== '8.5.0') throw new RuntimeException('Expected PHP 8.5.0, got ' . PHP_VERSION);
$names = json_decode(stream_get_contents(STDIN));
foreach ($names as $name) {
    $f = new ReflectionFunction($name);
    $params = []; $defaults = []; $byValue = [];
    foreach ($f->getParameters() as $p) {
        $text = (string) $p;
        $default = str_contains($text, ' = ') ? substr($text, strpos($text, ' = ') + 3, -2) : null;
        $defaults[] = $default;
        $byValue[] = $p->canBePassedByValue();
        $decl = '';
        foreach ($p->getAttributes() as $attr) {
            if ($attr->getName() === 'SensitiveParameter') $decl .= '#[SensitiveParameter] ';
        }
        if ($p->hasType()) $decl .= $p->getType() . ' ';
        if ($p->isPassedByReference()) $decl .= '&';
        if ($p->isVariadic()) $decl .= '...';
        $decl .= '$' . $p->getName();
        if ($default !== null) $decl .= ' = ' . ($default === '<default>' ? 'null' : $default);
        $params[] = $decl;
    }
    $decl = '<?php function ' . ($f->returnsReference() ? '&' : '') . '__native(' . implode(', ', $params) . ')';
    if ($f->hasReturnType()) $decl .= ': ' . $f->getReturnType();
    $decl .= ' {}';
    echo json_encode([$name, $f->getName(), $f->getExtensionName(), $decl, $defaults, $byValue]), "\n";
}
'''
rows = [json.loads(line) for line in subprocess.check_output(
    [str(args.php.resolve()), '-d', 'display_errors=stderr', '-r', extractor], input=json.dumps(names), text=True).splitlines()]

def rust(value):
    return json.dumps(value, ensure_ascii=False)

out = ['// Generated by tools/generate_native_signatures.py with PHP 8.5.0.',
       '// PHP signature metadata; see THIRD_PARTY_NOTICES.md.',
       'use super::native::NativeSignature;',
       'pub(super) fn lookup(name: &[u8]) -> Option<NativeSignature> {',
       'Some(match name {']
for key, name, extension, declaration, defaults, by_value in rows:
    default_text = ', '.join('None' if x is None else f'Some({rust(x)})' for x in defaults)
    flags = ', '.join(str(x).lower() for x in by_value)
    out.append(f'b{rust(key)} => NativeSignature {{ name: {rust(name)}, extension: {rust(extension)}, declaration: {rust(declaration)}, defaults: &[{default_text}], by_value: &[{flags}] }},')
out.extend(['_ => return None,', '})', '}'])
args.output.write_text('\n'.join(out) + '\n')
subprocess.run(['rustfmt', '--edition', '2024', str(args.output)], check=True)
print(f'Generated {len(rows)} native signatures')
