#!/usr/bin/env python3
"""Extract internal class/interface extension ownership from PHP 8.5.0."""
import argparse
import json
from pathlib import Path
import subprocess

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('php', type=Path)
parser.add_argument('--output', type=Path, default=Path('src/runtime/reflection/class_modules.rs'))
args = parser.parse_args()
code = r'''
if (PHP_VERSION !== '8.5.0') throw new RuntimeException('Expected PHP 8.5.0');
$result = [];
foreach (array_merge(get_declared_classes(), get_declared_interfaces()) as $name) {
    $r = new ReflectionClass($name);
    if ($r->isInternal()) $result[strtolower($name)] = $r->getExtensionName();
}
ksort($result); echo json_encode($result);
'''
rows = json.loads(subprocess.check_output([str(args.php.resolve()), '-r', code], text=True))
out = ['// Generated by tools/generate_class_modules.py with PHP 8.5.0.',
       '// PHP metadata; see THIRD_PARTY_NOTICES.md.',
       'pub(super) fn extension(name: &[u8]) -> Option<&\'static str> {',
       'Some(match name {']
for name, extension in rows.items():
    if extension is not False:
        out.append(f'b{json.dumps(name)} => {json.dumps(extension)},')
out.extend(['_ => return None,', '})', '}'])
args.output.write_text('\n'.join(out)+'\n')
subprocess.run(['rustfmt', '--edition', '2024', str(args.output)], check=True)
print(f'Generated {len(rows)} class/interface module mappings')
